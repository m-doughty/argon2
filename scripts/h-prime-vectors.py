#!/usr/bin/env python3
"""Generates tests/src/h_prime_vectors.ads: RFC 9106 section 3.3 H' outputs
computed with CPython's hashlib.blake2b, an oracle independent of the Ada
code and of the vendored C reference.

H' is written here straight from the RFC text: for T <= 64 it is the T-byte
BLAKE2b of LE32 (T) || A; for T > 64, with r = ceil (T / 32) - 2, V_1 is the
64-byte BLAKE2b of LE32 (T) || A, V_i the 64-byte BLAKE2b of V_(i-1), and the
output is the first 32 bytes of V_1 .. V_r followed by V_(r+1), the
(T - 32 r)-byte BLAKE2b of V_r.

Each case gives the input length, a seed and the output length T. Input
byte J is (Seed * 37 + J * 13 + (J >> 8) * 7) mod 256; the Ada test builds
the same input from the same formula. Outputs go up to 2**20 + 8 bytes, so
a case records the 32-byte BLAKE2b digest of the whole output (the test
hashes its own output the same way).

Usage (from the crate root, with an isolated interpreter):
  python3 -I scripts/h-prime-vectors.py           rewrite tests/src/h_prime_vectors.ads
  python3 -I scripts/h-prime-vectors.py --check   exit 1 if the file is stale
"""

import hashlib
import pathlib
import struct
import sys

INPUT_LENGTHS = (72, 1024)
OUTPUT_LENGTHS = (
    1, 4, 31, 32, 33, 63, 64, 65, 66, 95, 96, 97, 127, 128, 129,
    1023, 1024, 1025,
    # Around 2**16, and a tail of 63 (65535), of 33 (65537).
    65535, 65536, 65537,
    # 2**20, and 2**20 + 8, whose last link has 40 bytes.
    1048576, 1048584,
)
# Short and degenerate inputs at the lengths that matter for the tail.
EXTRA = [(0, 4), (0, 65), (1, 1), (1, 33), (127, 97), (128, 96), (129, 129)]

HEADER = """--  Generated by scripts/h-prime-vectors.py with CPython's hashlib.blake2b.
--  Do not edit: rerun the script instead.
--
--  Copyright (c) 2026, Matt Doughty
--  SPDX-License-Identifier: BSD-3-Clause

package H_Prime_Vectors is

   --  Input byte J is (Seed * 37 + J * 13 + (J / 256) * 7) mod 256.
   --  Digest is the hexadecimal BLAKE2b (32 bytes) of the whole H' output.
   type Vector is record
      Input_Length  : Natural;
      Seed          : Natural;
      Output_Length : Positive;
      Digest        : String (1 .. 64);
   end record;

   Vectors : constant array (Positive range <>) of Vector :=
     [
"""


def content(seed, length):
    return bytes((seed * 37 + j * 13 + (j >> 8) * 7) & 0xFF
                 for j in range(length))


def blake(data, size):
    return hashlib.blake2b(data, digest_size=size).digest()


def h_prime(a, t):
    prefix = struct.pack("<I", t)
    if t <= 64:
        return blake(prefix + a, t)
    r = (t + 31) // 32 - 2
    v = blake(prefix + a, 64)               # V_1
    out = b""
    for _ in range(r - 1):
        out += v[:32]
        v = blake(v, 64)
    out += v[:32]                           # V_r
    out += blake(v, t - 32 * r)             # V_(r+1)
    return out


def cases():
    seed = 0
    for n in INPUT_LENGTHS:
        for t in OUTPUT_LENGTHS:
            seed += 1
            yield n, seed, t
    for n, t in EXTRA:
        seed += 1
        yield n, seed, t


def render():
    lines = []
    for n, seed, t in cases():
        out = h_prime(content(seed, n), t)
        assert len(out) == t
        lines.append(
            "      (%d, %d, %d,\n"
            "       \"%s\")"
            % (n, seed, t, blake(out, 32).hex()))
    return HEADER + ",\n".join(lines) + "];\n\nend H_Prime_Vectors;\n"


def main(argv):
    root = pathlib.Path(__file__).resolve().parent.parent
    target = root / "tests" / "src" / "h_prime_vectors.ads"
    text = render()
    if argv == ["--check"]:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != text:
            print("tests/src/h_prime_vectors.ads is stale: rerun the script")
            return 1
        print("tests/src/h_prime_vectors.ads is current")
        return 0
    if argv:
        print(__doc__)
        return 2
    target.write_text(text, encoding="utf-8")
    print("wrote tests/src/h_prime_vectors.ads (%d cases)"
          % len(list(cases())))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
