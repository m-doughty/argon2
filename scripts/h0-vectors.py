#!/usr/bin/env python3
"""Generates tests/src/h0_vectors.ads: RFC 9106 H0 digests computed with
CPython's hashlib.blake2b, an oracle independent of the Ada code and of the
vendored C reference.

Each case gives the six 32-bit parameters (p, T, m, t, v, y), the lengths of
P, S, K and X, and a seed. Input I (0 for P .. 3 for X) holds, at
position J, the byte (Seed * 37 + I * 101 + J * 13 + (J >> 9) * 7) mod 256;
the Ada test builds the same inputs from the same formula.

Usage (from the crate root, with an isolated interpreter):
  python3 -I scripts/h0-vectors.py           rewrite tests/src/h0_vectors.ads
  python3 -I scripts/h0-vectors.py --check   exit 1 if the file is stale
"""

import hashlib
import pathlib
import struct
import sys

# (p, T, m, t, v, y, len P, len S, len K, len X, seed)
CASES = [
    # Every input empty: four empty pieces.
    (1, 4, 8, 1, 0x13, 2, 0, 0, 0, 0, 0),
    # One byte each.
    (1, 4, 8, 1, 0x13, 2, 1, 1, 1, 1, 1),
    # m not a multiple of 4p: m' = 36 would differ from m = 37.
    (3, 32, 37, 3, 0x13, 2, 32, 16, 8, 12, 2),
    (4, 32, 33, 3, 0x13, 1, 32, 16, 8, 12, 3),
    # Distinct, non-trivial values in every byte of every field.
    (0x00FFFFFF, 0xFFFFFFFF, 0x89ABCDEF, 0x01020304, 0x10, 0,
     5, 6, 7, 9, 4),
    (0x00010203, 0x04050607, 0x08090A0B, 0x0C0D0E0F, 0x13, 2,
     3, 0, 2, 0, 5),
    # Each input alone at the chunk boundaries (4096-byte chunks).
    (2, 64, 1024, 2, 0x13, 2, 4095, 16, 0, 0, 6),
    (2, 64, 1024, 2, 0x13, 2, 4096, 16, 0, 0, 7),
    (2, 64, 1024, 2, 0x13, 2, 4097, 16, 0, 0, 8),
    (2, 64, 1024, 2, 0x13, 2, 8193, 16, 0, 0, 9),
    (1, 32, 64, 1, 0x13, 2, 8, 4095, 0, 0, 10),
    (1, 32, 64, 1, 0x13, 2, 8, 4097, 0, 0, 11),
    (1, 32, 64, 1, 0x13, 2, 8, 16, 4096, 0, 12),
    (1, 32, 64, 1, 0x13, 2, 8, 16, 8192, 0, 13),
    (1, 32, 64, 1, 0x13, 2, 8, 16, 0, 4095, 14),
    (1, 32, 64, 1, 0x13, 2, 8, 16, 0, 4097, 15),
    # All four across a boundary.
    (8, 128, 4096, 4, 0x13, 2, 4097, 4097, 4097, 4097, 16),
    # Lengths around BLAKE2b's 128-byte block (127, 128, 129, 255, 300),
    # so that some fields straddle block boundaries.
    (1, 4, 8, 1, 0x13, 2, 127, 128, 129, 255, 17),
    (1, 4, 8, 1, 0x13, 2, 0, 1, 0, 300, 18),
]

HEADER = """--  Generated by scripts/h0-vectors.py with CPython's hashlib.blake2b.
--  Do not edit: rerun the script instead.
--
--  Copyright (c) 2026, Matt Doughty
--  SPDX-License-Identifier: BSD-3-Clause

with Interfaces;

package H0_Vectors is

   type Vector is record
      Parallelism, Tag_Length, Memory, Passes, Version, Kind :
        Interfaces.Unsigned_32;
      Password_Length, Salt_Length, Secret_Length, Data_Length : Natural;
      Seed : Natural;
      Digest : String (1 .. 128);
   end record;

   Vectors : constant array (Positive range <>) of Vector :=
     [
"""


def content(seed, index, length):
    return bytes((seed * 37 + index * 101 + j * 13 + (j >> 9) * 7) & 0xFF
                 for j in range(length))


def h0(case):
    p, t_len, m, t, v, y, lp, ls, lk, lx, seed = case
    message = struct.pack("<6I", p, t_len, m, t, v, y)
    for index, length in enumerate((lp, ls, lk, lx)):
        message += struct.pack("<I", length) + content(seed, index, length)
    return hashlib.blake2b(message, digest_size=64).hexdigest()


def render():
    lines = []
    for case in CASES:
        p, t_len, m, t, v, y, lp, ls, lk, lx, seed = case
        lines.append(
            "      (%d, %d, %d, %d, %d, %d,\n"
            "       %d, %d, %d, %d, %d,\n"
            "       \"%s\"\n"
            "       & \"%s\")"
            % (p, t_len, m, t, v, y, lp, ls, lk, lx, seed,
               h0(case)[:64], h0(case)[64:]))
    return HEADER + ",\n".join(lines) + "];\n\nend H0_Vectors;\n"


def main(argv):
    root = pathlib.Path(__file__).resolve().parent.parent
    target = root / "tests" / "src" / "h0_vectors.ads"
    text = render()
    if argv == ["--check"]:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != text:
            print("tests/src/h0_vectors.ads is stale: rerun the script")
            return 1
        print("tests/src/h0_vectors.ads is current")
        return 0
    if argv:
        print(__doc__)
        return 2
    target.write_text(text, encoding="utf-8")
    print("wrote tests/src/h0_vectors.ads (%d cases)" % len(CASES))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
